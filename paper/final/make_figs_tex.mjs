/* Writes numbers_figs.tex: plain numbers (no % sign, no thousands braces) for the bar chart, read from ../ieee/numbers.tex,
   which the research pipeline generates. The chart is drawn from these, so it can never disagree with the tables.
   Run:  node paper/final/make_figs_tex.mjs   */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, '..', 'ieee', 'numbers.tex'), 'utf8');
const get = name => {
  const m = src.match(new RegExp(`\\\\newcommand\\{\\\\${name}\\}\\{([^}]*(?:\\{[^}]*\\}[^}]*)*)\\}`));
  if (!m) throw new Error(`${name} is not in numbers.tex`);
  return Number(m[1].replace(/\\%/g, '').replace(/\{,\}/g, '').replace(/[^\d.]/g, ''));
};
const total = get('RefQuestionsAll');
const conds = [['A', 'Closed'], ['B', 'Feedback'], ['C', 'Name'], ['D', 'Topic'], ['E', 'TopicPrior']];
const lines = ['% GENERATED by make_figs_tex.mjs from ../ieee/numbers.tex. Do not edit.'];
for (const [k, c] of conds) {
  const n = get(`RefAll${c}`);
  lines.push(`\\newcommand{\\FigNamed${k}}{${n}}`, `\\newcommand{\\FigPct${k}}{${(100 * n / total).toFixed(1)}}`, `\\newcommand{\\FigVer${k}}{${get(`VerPctAll${c}`)}}`);
}
lines.push(`\\newcommand{\\FigAll}{${total}}`);
writeFileSync(join(here, 'numbers_figs.tex'), lines.join('\n') + '\n');
console.log(lines.join('\n'));
