/* Writes paper/final/numbers_case.tex: every number that the worked-case and workspace sections quote, generated from
   case_results.json, grounding_results.json, the workspace's own modules and its test suites. Never edit the .tex by hand.
   Run after run_case.mjs and run_grounding.mjs:  node paper/final/case_study/make_case_tex.mjs   */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..', '..');
const require = createRequire(join(repo, 'lawyerai', 'package.json'));
const Limitation = require('./limitation.js');
const Drafting = require('./drafting.js');
const caseRes = JSON.parse(readFileSync(join(here, 'case_results.json'), 'utf8'));
const ground = JSON.parse(readFileSync(join(here, 'grounding_results.json'), 'utf8'));

const lines = [];
const num = n => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, '{,}');
const def = (name, value) => lines.push(`\\newcommand{\\${name}}{${value}}`);
const longDate = iso => { const [y, m, d] = iso.split('-').map(Number); return `${d} ${['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'][m - 1]} ${y}`; };
const sum = (xs, f) => xs.reduce((a, x) => a + (f(x) || 0), 0);

/* reading, citation check, limitation */
const r = caseRes.reading;
def('CaseJudgWords', num(r.judgment.words)); def('CaseJudgDates', r.judgment.dates); def('CaseJudgAmounts', r.judgment.amounts); def('CaseJudgExhibit', r.judgment.exhibit59);
def('CaseStmtWords', num(r.statements.words)); def('CaseStmtDates', r.statements.dates); def('CaseStmtExhibit', r.statements.exhibit59);
def('CaseOrdersWords', num(r.orders.words)); def('CaseOrdersDates', r.orders.dates);
def('CaseInconsistencies', r.inconsistencies);
const items = caseRes.citations.items, by = s => items.filter(i => i.status === s).length;
def('CaseCiteFound', items.length); def('CaseCiteVerified', by('verified')); def('CaseCiteWrongNumber', by('wrong-number'));
def('CaseCiteMisattributed', by('misattributed')); def('CaseCiteNotFound', by('not-found')); def('CaseCiteUncheckable', by('uncheckable'));
def('CaseLimitStart', longDate(caseRes.limitation.start)); def('CaseLimitDate', longDate(caseRes.limitation.lastDate));

/* the table of the planted-error draft (generated, so it can never disagree with the run) */
const tex = s => String(s).replace(/\\/g, '\\textbackslash{}').replace(/([&%$#_{}])/g, '\\$1').replace(/\u00B7/g, '\\textperiodcentered{}');
const VERDICT = { verified: 'Confirmed', 'wrong-number': 'Wrong number', misattributed: 'Number of another case', 'not-found': 'Not found', uncheckable: 'High Court, not checkable' };
const rows = items.map(i => `${tex(i.cited)} & ${i.citation ? tex(i.citation) : '(name only)'} & ${VERDICT[i.status] || tex(i.status)} \\\\`);
const col = w => `>{\\raggedright\\arraybackslash}p{${w}in}`;
writeFileSync(join(here, '..', 'tab_case.tex'), `% GENERATED by case_study/make_case_tex.mjs. Do not edit.\n\\begin{tabular}{@{}${col(1.3)}${col(0.95)}${col(0.85)}@{}}\n\\toprule\nCase as cited & Citation & Verdict \\\\\n\\midrule\n${rows.join('\n')}\n\\bottomrule\n\\end{tabular}\n`);

/* grounding checks on a small local model */
const ok = name => ground.runs[name].filter(x => !x.error);
const m = ok('contradiction-matrix'), d = ok('order-digest'), t = ok('timeline-depositions');
def('GroundModel', 'Qwen2.5-VL 7B'); def('GroundRuns', ground.seeds.length);
def('GroundMatrixRuns', m.length); def('GroundMatrixProposed', sum(m, x => x.proposed)); def('GroundMatrixKept', sum(m, x => x.kept)); def('GroundMatrixDropped', sum(m, x => x.dropped));
def('GroundDigestRuns', d.length); def('GroundDigestInvented', d.filter(x => x.stated === false).length);
const digestDates = d.filter(x => /^\d{4}-\d{2}-\d{2}$/.test(x.rawNextDate)).map(x => longDate(x.rawNextDate));
const counted = [...new Set(digestDates)].map(x => { const n = digestDates.filter(y => y === x).length; return n > 1 ? `${x} (${n} runs)` : x; });
def('GroundDigestDates', counted.length > 1 ? `${counted.slice(0, -1).join(', ')} and ${counted.at(-1)}` : (counted[0] || 'none'));
def('GroundMatrixEmptyRuns', m.filter(x => x.proposed === 0).length);
def('GroundTimelineFailed', ground.runs['timeline-depositions'].filter(x => x.error).length);
def('GroundTimelineRuns', t.length); def('GroundTimelineProposed', sum(t, x => x.proposedEvents)); def('GroundTimelineKept', sum(t, x => x.keptEvents)); def('GroundTimelineDropped', sum(t, x => x.droppedEvents));
def('GroundIsoProposed', sum(t, x => x.isoDatesProposed)); def('GroundIsoMissing', sum(t, x => x.isoDatesNotInDocuments));
def('GroundSourcesNamed', sum(t, x => x.sourcesNamed)); def('GroundSourcesInvented', sum(t, x => x.sourcesNotADocument));
def('GroundQDocsNamed', sum(t, x => x.questionDocsNamed)); def('GroundQDocsInvented', sum(t, x => x.questionDocsNotADocument));
{ const a = sum(t, x => x.sourcesNotADocument), b = sum(t, x => x.questionDocsNotADocument);
  def('GroundSuppliedClause', a + b === 0 ? 'every one was a document we had supplied' : `${a} of the sources and ${b} of the documents were not documents we had supplied`); }

/* the workspace itself */
def('CasePeriods', Limitation.RULES.length); def('CaseFormats', Drafting.BUILTIN_FORMATS.length);
const tests = dir => { const p = spawnSync(process.execPath, ['--test'], { cwd: join(repo, dir), encoding: 'utf8', timeout: 600000 }); const g = k => Number((p.stdout.match(new RegExp(`^# ${k} (\\d+)`, 'm')) || [])[1]); if (g('fail') !== 0) throw new Error(`${dir}: tests failed`); return g('pass'); };
def('CaseTestsWorkspace', tests('lawyerai')); def('CaseTestsApi', tests('caselaw-db'));

writeFileSync(join(here, '..', 'numbers_case.tex'), `% GENERATED by case_study/make_case_tex.mjs. Do not edit.\n${lines.join('\n')}\n`);
console.log(lines.join('\n'));
